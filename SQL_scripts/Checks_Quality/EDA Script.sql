/* =============== step 3 Date exploration ============================= */
-- identify the earliest and latest dates boundaries.understand the scope data and timespan --
-- with the help of this we can analysis year related 

select 
min(order_date) as strtdate, 
max(order_Date) as lastdate,
DATEDIFF(year,min(order_date), max(order_Date)) as yeargap
from 
[dbo].[gold_fact_sales]  -- finding how many years sales are available by checking first  and last order date

select 
min(birth_Date) as oldest,
max(birth_Date) as youngest,
DATEDIFF(year,min(birth_Date),getdate()) as oldest_age,
DATEDIFF(year,max(birth_Date),getdate()) as youngest_age
from [dbo].[gold_dim_customer]  -- find the youngest and oldest customers

/* =============== step 4 Measures exploration ============================= */
-- calculate the key metric of the business (big numbers) 
-- highest levlel of aggregation | lowest level of details 

select sum(sales_amount) as totalsales from [dbo].[gold_fact_sales]

select sum(quantity) as totalsales from [dbo].[gold_fact_sales]

select avg(price) as totalsales from [dbo].[gold_fact_sales]

select count(order_number) as totalorder from [dbo].[gold_fact_sales]
select count(distinct order_number) as totalorder from [dbo].[gold_fact_sales]

select count(product_key) as totalproduct from gold_dim_product
select count(distinct product_key) as totaluniqueproduct from gold_dim_product

select count(customer_key) from [dbo].[gold_dim_customer]
select count(distinct customer_key) from [dbo].[gold_dim_customer]

select customer_key from [dbo].[gold_dim_customer]
where customer_key not in 
(select customer_key from [dbo].[gold_fact_sales])

