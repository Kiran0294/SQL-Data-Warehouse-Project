/* =============== step 5 Magnitude exploration ============================= */
-- compare the measure values against dimension , it help us understand  the importance of different categories

select country, count(customer_key) as total_customer_by_country from [dbo].[gold_dim_customer]
group by country order by total_customer_by_country desc

select gender, count(customer_key) as total_customer_by_gender from [dbo].[gold_dim_customer]
group by gender order by total_customer_by_gender desc

select * from [dbo].[gold_dim_product]
select category, count(product_key) as total_prod_by_cat from [dbo].[gold_dim_product]
group by category order by total_prod_by_cat desc

select category, avg(cost) as avg_cost_by_category from [dbo].[gold_dim_product]
group by category order by avg_cost_by_category desc

select category, sum(cost) as total_revenue_by_category from [dbo].[gold_dim_product]
group by category order by total_revenue_by_category desc

select
pr.category,
sum(sl.sales_amount) as total_revenue
from [dbo].[gold_fact_sales] sl
left join     [dbo].[gold_dim_product] pr
on            sl.product_key=pr.product_key
group by pr.category
order by total_revenue -- total revenue generated by each category

